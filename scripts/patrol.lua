--  версию сама (hot-reload, галочка auto-restart в редакторе).
--
--  Что здесь есть:
--    move(x, y)          — приказ ехать в точку (в юнитах мира,
--                          Y — «север»); исполняется несколько тиков
--    scan(radius)        — скан окрестности (занимает 5 тиков)
--    print("...")        — строка в консоль игры (клавиша ` )
--    coroutine.yield()   — «уснуть до следующего тика»
-- ============================================================

-- Сторона квадрата patrol-маршрута, в юнитах мира.
local SIDE = 8

-- Сколько тиков постоять на каждой вершине: пока едет скан,
-- ровер успевает «оглядеться». Можешь поставить 0 — поедет без пауз.
local PAUSE = 10

-- Одна вершина маршрута: доехать, просканировать, доложить, подождать.
-- Команды move/scan НЕ исполняются мгновенно — они встают в очередь
-- ровера, и мир применяет их на своих тиках (30 тиков в секунду).
local function visit(x, y)
	move(x, y)
	scan(3.0)
	print("патруль: вершина (" .. x .. ", " .. y .. ")")
	for _ = 1, PAUSE do
		coroutine.yield()
	end
end

-- Квадрат против часовой стрелки вокруг стартовой площадки.
-- Маршрут бесконечный — это патруль. Остановить можно кнопкой Stop.
while true do
	visit(0, 0)
	visit(SIDE, 0)
	visit(SIDE, SIDE)
	visit(0, SIDE)
end
